import Foundation

struct StructureStage: Identifiable, Hashable {
    let id: String
    let name: String
    let purpose: String
    let choiceFocus: String
}

struct StoryStructureTemplate: Identifiable, Hashable {
    let id: String
    let name: String
    let subtitle: String
    let family: String
    let icon: String
    let tintName: String
    let experience: String
    let bestFor: String
    let caution: String
    let strictness: Int
    let stages: [StructureStage]
    let sourceReferences: [String]

    var rulesPrompt: String {
        let rules = stages.enumerated().map { index, stage in
            "\(index + 1). \(stage.name)：\(stage.purpose) 选择焦点：\(stage.choiceFocus)"
        }.joined(separator: "\n")
        return """
        结构模板：\(name)
        核心体验：\(experience)
        适合：\(bestFor)
        注意：\(caution)
        阶段规则：
        \(rules)
        理论来源：\(sourceReferences.joined(separator: "；"))
        """
    }
}

