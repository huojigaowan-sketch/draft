    static var defaultTemplate: StoryStructureTemplate { templates[0] }

    static func template(id: String) -> StoryStructureTemplate {
        templates.first { $0.id == id } ?? defaultTemplate
    }

    private static func template(
        _ id: String,
        _ name: String,
        _ subtitle: String,
        _ family: String,
        _ icon: String,
        _ tintName: String,
        _ strictness: Int,
        _ experience: String,
        _ bestFor: String,
        _ caution: String,
        _ stages: [StructureStage],
        _ sources: [String]
    ) -> StoryStructureTemplate {
        StoryStructureTemplate(
            id: id,
            name: name,
            subtitle: subtitle,
            family: family,
            icon: icon,
            tintName: tintName,
            experience: experience,
            bestFor: bestFor,
            caution: caution,
            strictness: strictness,
            stages: stages,
            sourceReferences: sources
        )
    }

    private static func stage(
        _ id: String,
        _ name: String,
        _ purpose: String,
        _ choiceFocus: String
    ) -> StructureStage {
        StructureStage(id: id, name: name, purpose: purpose, choiceFocus: choiceFocus)
    }
